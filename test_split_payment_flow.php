 * 
 * --------------------------------------------------------------------------
 * 1. إنشاء أوردر جديد (neworder)
 * --------------------------------------------------------------------------
 * Endpoint: POST {{url}}/api/v1/order/new
 * Body (JSON):
 {
    "service_id": 1,
    "source_lat": "30.0444",
    "source_long": "31.2357",
    "source_address": "Cairo, Egypt",
    "destination_lat": "30.0131",
    "destination_long": "31.2089",
    "destination_address": "Giza, Egypt",
    "payment_type": "wallet_card",
    "saved_card_id": 5,
    "amount": 100,
    "offer_rate": 100,
    "inter_city": 0,
    "is_female_only": 0
 }
 * 
 * القيمة المتاحة للـ payment_type:
 * 1. cash         -> كاش بالكامل للخارج. عمولة الشركة بتتخصم من السواق في البداية.
 * 2. wallet       -> خصم كامل من محفظة العميل.
 * 3. saved_card   -> خصم كامل من الكارت المحفوظ (اللي معاه ID أو الـ default).
 * 4. card         -> (نفس الـ saved_card حالياً) بيسحب من الكارت المحفوظ.
 * 5. wallet_card  -> (Split) بياخد كل اللي في المحفظة والباقي من الكارت المحفوظ.
 * 6. wallet_cash  -> (Split) بياخد كل اللي في المحفظة والباقي العميل بيدفعه للسواق كاش.
 * 
 * --------------------------------------------------------------------------
 * 2. السواق يبعت عرض (offerdriver)
 * --------------------------------------------------------------------------
 * Endpoint: POST {{url}}/api/v1/order/add-out-city-offer/{{order_id}}/{{offer_rate}}
 * (للمعلمومة: ده للرحلات خارج المدينة، لمزيد من التجربة استخدم negotiation flow لو محتاج)
 * 
 * --------------------------------------------------------------------------
 * 3. العميل يقبل العرض (acceptOffer) - "هنا بيتم الخصم"
 * --------------------------------------------------------------------------
 * Endpoint: POST {{url}}/api/v1/order/offer/{{offer_id}}/accept
 * Body (JSON):
 {
    "order_id": 15
 }
 * 
 * --------------------------------------------------------------------------
 * 4. السواق يضغط "وصلت للعميل" (arrivedorder)
 * --------------------------------------------------------------------------
 * Endpoint: POST {{url}}/api/v1/order/arrived/{{order_id}}
 * Body (JSON):
 {
    "order_id": 15
 }
 * 
 * --------------------------------------------------------------------------
 * 5. السواق يضغط "بدء الرحلة" (startorder)
 * --------------------------------------------------------------------------
 * Endpoint: GET {{url}}/api/v1/order/start/{{order_id}}
 * (العمولة بتتخصم هنا في الكاش)
 * 
 * --------------------------------------------------------------------------
 * 6. السواق يضغط "إنهاء الرحلة" (endorder) 
 * --------------------------------------------------------------------------
 * Endpoint: GET {{url}}/api/v1/order/end/{{order_id}}
 * 
 * --------------------------------------------------------------------------
 * 7. إلغاء الرحلة (cancelorder)
 * --------------------------------------------------------------------------
 * Endpoint: GET {{url}}/api/v1/order/cancel/{{order_id}}
